#!/usr/bin/env node
// Generates supabase/migrations/20260925000016_reference_data.sql from
// scripts/data/*.mjs. Re-run after editing the data files:
//   node scripts/generate-reference-sql.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { REGIONS, DISTRICTS } from "./data/uz-locations.mjs";
import { CATEGORIES, SKILLS } from "./data/catalog.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "supabase/migrations/20260925000016_reference_data.sql");

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const arr = (xs) => `array[${xs.map(q).join(", ")}]::text[]`;

const lines = [];
lines.push("-- GENERATED by scripts/generate-reference-sql.mjs — do not edit by hand.");
lines.push("-- Reference data required in every environment (production included):");
lines.push("-- country, regions, districts, profession catalogue, plans, paid services, settings.");
lines.push("");
lines.push("insert into public.countries (code, name_uz, name_ru, name_en) values ('UZ', 'Oʻzbekiston', 'Узбекистан', 'Uzbekistan')");
lines.push("on conflict (code) do nothing;");
lines.push("");

lines.push("insert into public.regions (country_id, slug, name_uz, name_ru, name_en, lat, lng, sort_order) values");
lines.push(
  REGIONS.map(
    (r, i) =>
      `  ((select id from public.countries where code = 'UZ'), ${q(r.slug)}, ${q(r.nameUz)}, ${q(r.nameRu)}, ${q(r.nameEn)}, ${r.lat}, ${r.lng}, ${i + 1})`,
  ).join(",\n") + "\non conflict (slug) do nothing;",
);
lines.push("");

lines.push("insert into public.districts (region_id, slug, kind, name_uz, lat, lng)");
lines.push("select r.id, d.slug, d.kind::public.district_kind, d.name_uz, d.lat, d.lng from (values");
const drows = [];
for (const [regionSlug, list] of Object.entries(DISTRICTS)) {
  for (const d of list) {
    drows.push(`  (${q(regionSlug)}, ${q(d.slug)}, ${q(d.kind)}, ${q(d.nameUz)}, ${d.lat}, ${d.lng})`);
  }
}
lines.push(drows.join(",\n"));
lines.push(") as d(region_slug, slug, kind, name_uz, lat, lng)");
lines.push("join public.regions r on r.slug = d.region_slug");
lines.push("on conflict (region_id, slug) do nothing;");
lines.push("");

lines.push("insert into public.skills (slug, name_uz) values");
lines.push(SKILLS.map(([slug, name]) => `  (${q(slug)}, ${q(name)})`).join(",\n") + "\non conflict (slug) do nothing;");
lines.push("");

lines.push("insert into public.categories (slug, name_uz, name_ru, icon, sort_order) values");
lines.push(
  CATEGORIES.map((c, i) => `  (${q(c.slug)}, ${q(c.name)}, ${q(c.nameRu)}, ${q(c.icon)}, ${i + 1})`).join(",\n") +
    "\non conflict (slug) do nothing;",
);
lines.push("");

const prow = [];
const psrow = [];
for (const c of CATEGORIES) {
  c.professions.forEach(([slug, name, nameRu, synonyms, skills], i) => {
    prow.push(`  (${q(c.slug)}, ${q(slug)}, ${q(name)}, ${q(nameRu)}, ${arr(synonyms)}, ${i + 1})`);
    for (const s of skills) psrow.push(`  (${q(slug)}, ${q(s)})`);
  });
}
lines.push("insert into public.professions (category_id, slug, name_uz, name_ru, synonyms, sort_order)");
lines.push("select c.id, p.slug, p.name_uz, p.name_ru, p.synonyms, p.sort_order from (values");
lines.push(prow.join(",\n"));
lines.push(") as p(category_slug, slug, name_uz, name_ru, synonyms, sort_order)");
lines.push("join public.categories c on c.slug = p.category_slug");
lines.push("on conflict (slug) do nothing;");
lines.push("");
lines.push("insert into public.profession_skills (profession_id, skill_id)");
lines.push("select p.id, s.id from (values");
lines.push(psrow.join(",\n"));
lines.push(") as x(profession_slug, skill_slug)");
lines.push("join public.professions p on p.slug = x.profession_slug");
lines.push("join public.skills s on s.slug = x.skill_slug");
lines.push("on conflict do nothing;");
lines.push("");

lines.push(`insert into public.subscription_plans (code, audience, name_uz, description_uz, price_uzs, interval_months, limits, features, sort_order) values
  ('FREE', 'employer', 'Bepul', 'Platformani sinab koʻrish uchun', 0, 1,
   '{"max_active_vacancies": 2, "advanced_filters": false, "contact_tools": false, "analytics": false, "recruiters": 1, "match_view_limit": 5}',
   '["2 ta faol vakansiya", "Asosiy qidiruv", "Ichki chat"]', 1),
  ('BASIC', 'employer', 'Basic', 'Kichik biznes uchun', 99000, 1,
   '{"max_active_vacancies": 5, "advanced_filters": true, "contact_tools": false, "analytics": false, "recruiters": 1, "match_view_limit": 20}',
   '["5 ta faol vakansiya", "Kengaytirilgan filtrlar", "20 ta mos nomzod tavsiyasi"]', 2),
  ('PRO', 'employer', 'Pro', 'Faol yollovchi kompaniyalar uchun', 249000, 1,
   '{"max_active_vacancies": 20, "advanced_filters": true, "contact_tools": true, "analytics": true, "recruiters": 3, "match_view_limit": 100}',
   '["20 ta faol vakansiya", "Nomzodlar bilan bogʻlanish vositalari", "Analitika", "3 ta rekruter"]', 3),
  ('BUSINESS', 'employer', 'Business', 'Yirik kompaniyalar va agentliklar uchun', 690000, 1,
   '{"max_active_vacancies": 100, "advanced_filters": true, "contact_tools": true, "analytics": true, "recruiters": 20, "match_view_limit": 300, "priority_support": true}',
   '["100 ta faol vakansiya", "20 ta rekruter", "Kompaniya sahifasi", "Ustuvor qoʻllab-quvvatlash"]', 4)
on conflict (code) do nothing;`);
lines.push("");
lines.push(`insert into public.paid_services (code, audience, name_uz, description_uz, price_uzs, duration_days) values
  ('vacancy_promotion', 'employer', 'Vakansiyani koʻtarish', 'Vakansiya oʻz hududidagi qidiruvda yuqorida koʻrsatiladi', 29000, 7),
  ('vacancy_premium', 'employer', 'Premium vakansiya', 'Ajratilgan dizayn, TOP belgisi va 30 kun yuqori oʻrin', 79000, 30),
  ('featured_employer', 'employer', 'Tavsiya etilgan ish beruvchi', 'Kompaniya bosh sahifada koʻrsatiladi', 149000, 30),
  ('candidate_premium', 'candidate', 'Premium profil', 'Profilingiz ish beruvchilarga birinchi koʻrsatiladi', 19000, 30),
  ('recruitment_package', 'employer', 'Rekruting xizmati', 'Mutaxassislarimiz siz uchun nomzodlarni saralab beradi', 990000, 30)
on conflict (code) do nothing;`);
lines.push("");
lines.push(`insert into public.app_settings (key, value, description, is_public) values
  ('matching.weights', '{"location": 25, "distance": 10, "profession": 20, "skills": 15, "experience": 10, "availability": 5, "salary": 5, "rating": 5, "completeness": 5}',
   'Moslik balli (MATCH SCORE) omillari vaznlari', true),
  ('moderation.auto_publish', 'true', 'Yangi vakansiyalar avtomatik eʼlon qilinsinmi (false = moderator tasdiqlaydi)', false),
  ('moderation.auto_hide_reports', '5', 'Nechta shikoyatdan keyin vakansiya vaqtincha yashiriladi', false),
  ('vacancy.default_duration_days', '30', 'Vakansiya amal qilish muddati (kun)', true),
  ('search.default_radius_km', '50', 'Standart qidiruv radiusi (km)', true)
on conflict (key) do nothing;`);
lines.push("");

writeFileSync(out, lines.join("\n"));
console.log(`wrote ${path.relative(root, out)} (${drows.length} districts, ${prow.length} professions, ${SKILLS.length} skills)`);
