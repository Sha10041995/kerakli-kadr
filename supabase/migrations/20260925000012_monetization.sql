create policy services_read on public.paid_services for select using (is_active or public.is_admin());
create policy services_admin on public.paid_services for all using (public.is_admin()) with check (public.is_admin());

create policy subscriptions_read on public.subscriptions for select
  using (user_id = auth.uid() or (company_id is not null and public.is_company_member(company_id)) or public.is_admin());
