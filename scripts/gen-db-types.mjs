#!/usr/bin/env node
// Generates src/types/database.ts (supabase-js compatible) by introspecting a
// database that has all migrations applied — e.g. the local test database:
//   npm run test:db -- --setup-only && npm run db:types
// Equivalent to `supabase gen types typescript`, but works without Docker.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import pg from "pg";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const url = process.env.TYPES_DATABASE_URL ?? "postgres://postgres:postgres@localhost:5432/kadrtop_test";
const client = new pg.Client({ connectionString: url });
await client.connect();

const enums = new Map();
for (const row of (
  await client.query(`
    select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' group by t.typname order by t.typname`)
).rows) {
  enums.set(row.name, row.labels);
}

const scalar = (udt) => {
  const t = udt.replace(/^_/, "");
  if (enums.has(t)) return `Database["public"]["Enums"]["${t}"]`;
  switch (t) {
    case "int2":
    case "int4":
    case "int8":
    case "float4":
    case "float8":
    case "numeric":
    case "oid":
      return "number";
    case "bool":
      return "boolean";
    case "json":
    case "jsonb":
      return "Json";
    case "void":
      return "undefined";
    case "record":
      return "Record<string, unknown>";
    default:
      return "string";
  }
};
const tsType = (udt) => (udt.startsWith("_") ? `${scalar(udt)}[]` : scalar(udt));

const relations = (
  await client.query(`
    select c.relname as name, c.relkind as kind
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind in ('r', 'v') order by c.relname`)
).rows;

const columns = (
  await client.query(`
    select table_name, column_name, udt_name, is_nullable = 'YES' as nullable,
           column_default is not null as has_default, is_identity = 'YES' as identity,
           identity_generation, is_generated = 'ALWAYS' as generated
    from information_schema.columns
    where table_schema = 'public'
    order by table_name, ordinal_position`)
).rows;

const fks = (
  await client.query(`
    select con.conname, src.relname as source, tgt.relname as target,
      array(select a.attname::text from unnest(con.conkey) with ordinality k(n, i)
            join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.n order by k.i) as cols,
      array(select a.attname::text from unnest(con.confkey) with ordinality k(n, i)
            join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.n order by k.i) as refcols,
      exists (select 1 from pg_constraint u where u.conrelid = con.conrelid and u.contype in ('p', 'u')
              and u.conkey::int[] @> con.conkey::int[] and u.conkey::int[] <@ con.conkey::int[]) as one_to_one
    from pg_constraint con
    join pg_class src on src.oid = con.conrelid
    join pg_class tgt on tgt.oid = con.confrelid
    join pg_namespace n on n.oid = src.relnamespace
    where con.contype = 'f' and n.nspname = 'public'
    order by con.conname`)
).rows;

const functions = (
  await client.query(`
    select p.proname as name, p.proretset as retset, rt.typname as rettype, p.pronargdefaults as ndefaults,
      p.pronargs as nargs,
      coalesce(p.proargnames, '{}') as argnames,
      coalesce(p.proargmodes::text[], '{}') as argmodes,
      array(select t.typname::text from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality a(oid, i)
            join pg_type t on t.oid = a.oid order by a.i) as argtypes
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    join pg_type rt on rt.oid = p.prorettype
    where n.nspname = 'public' and rt.typname <> 'trigger' and p.prokind = 'f'
    order by p.proname`)
).rows;

await client.end();

const ind = (n) => "  ".repeat(n);
const out = [];
out.push("// GENERATED by scripts/gen-db-types.mjs — do not edit by hand.");
out.push("// Regenerate: npm run test:db -- --setup-only && npm run db:types");
out.push("");
out.push("export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];");
out.push("");
out.push("export type Database = {");
out.push(`${ind(1)}public: {`);

for (const section of ["Tables", "Views"]) {
  out.push(`${ind(2)}${section}: {`);
  for (const rel of relations.filter((r) => (section === "Tables" ? r.kind === "r" : r.kind === "v"))) {
    const cols = columns.filter((c) => c.table_name === rel.name);
    out.push(`${ind(3)}${rel.name}: {`);
    out.push(`${ind(4)}Row: {`);
    for (const c of cols) out.push(`${ind(5)}${c.column_name}: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};`);
    out.push(`${ind(4)}};`);
    for (const kind of ["Insert", "Update"]) {
      out.push(`${ind(4)}${kind}: {`);
      for (const c of cols) {
        if ((c.identity && c.identity_generation === "ALWAYS") || c.generated) {
          out.push(`${ind(5)}${c.column_name}?: never;`);
          continue;
        }
        const optional = kind === "Update" || section === "Views" || c.nullable || c.has_default || c.identity;
        out.push(`${ind(5)}${c.column_name}${optional ? "?" : ""}: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};`);
      }
      out.push(`${ind(4)}};`);
    }
    const rels = fks.filter((f) => f.source === rel.name);
    out.push(`${ind(4)}Relationships: [`);
    for (const f of rels) {
      out.push(`${ind(5)}{`);
      out.push(`${ind(6)}foreignKeyName: "${f.conname}";`);
      out.push(`${ind(6)}columns: [${f.cols.map((c) => `"${c}"`).join(", ")}];`);
      out.push(`${ind(6)}isOneToOne: ${f.one_to_one};`);
      out.push(`${ind(6)}referencedRelation: "${f.target}";`);
      out.push(`${ind(6)}referencedColumns: [${f.refcols.map((c) => `"${c}"`).join(", ")}];`);
      out.push(`${ind(5)}},`);
    }
    out.push(`${ind(4)}];`);
    out.push(`${ind(3)}};`);
  }
  out.push(`${ind(2)}};`);
}

out.push(`${ind(2)}Functions: {`);
const seen = new Set();
for (const fn of functions) {
  if (seen.has(fn.name)) continue; // overloads are not used by the app
  seen.add(fn.name);
  const modes = fn.argmodes.length ? fn.argmodes : fn.argtypes.map(() => "i");
  const inputs = [];
  const outputs = [];
  modes.forEach((m, i) => {
    const entry = { name: fn.argnames[i] || `arg${i}`, type: fn.argtypes[i] };
    if (m === "i" || m === "b" || m === "v") inputs.push(entry);
    if (m === "o" || m === "t" || m === "b") outputs.push(entry);
  });
  // skip functions taking composite row types (internal helpers)
  if (inputs.some((a) => relations.some((r) => r.name === a.type))) continue;
  const firstDefault = inputs.length - Number(fn.ndefaults);
  out.push(`${ind(3)}${fn.name}: {`);
  if (inputs.length === 0) {
    out.push(`${ind(4)}Args: Record<PropertyKey, never>;`);
  } else {
    out.push(`${ind(4)}Args: {`);
    inputs.forEach((a, i) => {
      const opt = i >= firstDefault;
      out.push(`${ind(5)}${a.name}${opt ? "?" : ""}: ${tsType(a.type)}${opt ? " | null" : ""};`);
    });
    out.push(`${ind(4)}};`);
  }
  let ret;
  if (outputs.length) {
    ret = `{\n${outputs.map((o) => `${ind(5)}${o.name}: ${tsType(o.type)} | null;`).join("\n")}\n${ind(4)}}${fn.retset ? "[]" : ""}`;
  } else {
    ret = tsType(fn.rettype) + (fn.retset ? "[]" : "");
  }
  out.push(`${ind(4)}Returns: ${ret};`);
  out.push(`${ind(3)}};`);
}
out.push(`${ind(2)}};`);

out.push(`${ind(2)}Enums: {`);
for (const [name, labels] of enums) out.push(`${ind(3)}${name}: ${labels.map((l) => `"${l}"`).join(" | ")};`);
out.push(`${ind(2)}};`);
out.push(`${ind(2)}CompositeTypes: Record<string, never>;`);
out.push(`${ind(1)}};`);
out.push("};");
out.push("");
out.push('type PublicSchema = Database["public"];');
out.push('export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];');
out.push('export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];');
out.push('export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];');
out.push('export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];');
out.push('export type FunctionReturns<T extends keyof PublicSchema["Functions"]> = PublicSchema["Functions"][T]["Returns"];');
out.push("");

const target = path.join(root, "src/types/database.ts");
writeFileSync(target, out.join("\n"));
console.log(`wrote ${path.relative(root, target)} (${relations.length} relations, ${seen.size} functions, ${enums.size} enums)`);
